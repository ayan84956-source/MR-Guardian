from collections import defaultdict
from mr_guardian.review.schemas import ReviewResult

class ReportGenerator:

    def generate_markdown(self, review: ReviewResult) -> str:
        lines = []

        lines.append("# MR Guardian Code Report")
        lines.append("")

        lines.append(
            f"**Overall Risk:** {review.overall_risk.upper()}"
        )
        lines.append(
            f"**Review Status:** {review.review_status.upper()}"
        )
        lines.append("")

        lines.append("## Summary")
        lines.append(review.summary)
        lines.append("")

        lines.append("## Review Statistics")

        for key, value in review.statistics.items():
            lines.append(
                f"- **{key.replace('_', ' ').title()}:** {value}"
            )

        lines.append("")

        if not review.findings:
            lines.append("## No Issues Found")
            lines.append("")
            lines.append("---")
            lines.append("Generated by MR Guardian")
            return "\n".join(lines)

        group_findings = defaultdict(list)

        for finding in review.findings:

            if isinstance(finding, tuple):
                finding = finding[-1]

            if isinstance(finding, dict):
                source = finding.get("file_path") or "Unknown"
            else:
                source = getattr(finding, "file_path", None) or "Unknown"

            group_findings[source].append(finding)

        for source, findings in group_findings.items():

            lines.append("")
            lines.append(f"## {source.upper()} Findings")

            for index, finding in enumerate(findings, start=1):

                if isinstance(finding, dict):
                    get_value = finding.get
                else:
                    get_value = lambda key, default=None: getattr(
                        finding, key, default
                    )

                title = get_value("title", "Untitled Finding")
                severity = get_value("severity", "Unknown")
                category = get_value("category", "Unknown")
                file_path = get_value("file_path", "Unknown")
                line_number = get_value("line_number", "Unknown")
                description = get_value("description", "No description")
                recommendation = get_value(
                    "recommendation", "No recommendation"
                )

                lines.append("")
                lines.append(f"### {index}. {title}")
                lines.append(f"- **Severity:** {severity}")
                lines.append(f"- **Category:** {category}")
                lines.append(f"- **File:** {file_path}")
                lines.append(f"- **Line:** {line_number}")
                lines.append(f"- **Description:** {description}")
                lines.append(f"- **Recommendation:** {recommendation}")

        lines.append("")
        lines.append("---")
        lines.append("Generated by MR Guardian")

        return "\n".join(lines)